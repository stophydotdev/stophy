import { rmSync } from "node:fs";
import { z } from "zod";
import { type Json, type JsonObject, isObject, isString, json, jsonObject } from "./catalog";
import { mdxSafe, recorded, referenceConfig } from "./reference";
import { curlSnippet, pythonSnippet, tsSnippet } from "./snippets";

const root = new URL("..", import.meta.url);
const file = (path: string) => new URL(path, root);
const PARSERS_URL = process.env.STOPHY_PARSERS_URL ?? "https://api.stophy.dev/v1/parsers";
const GENERATED = "{/* Generated by scripts/gen-parsers.ts. Do not edit. */}";
const OVERVIEW = "scrape/prebuilt-parsers";
const SAMPLE = "youtube-transcript";
const SHARED_FROM = 3;

const option = z.object({ name: z.string(), description: z.string().optional() });
const parser = z.object({
  name: z.string(),
  takes: z.string(),
  example: z.string(),
  options: z.array(option),
  returns: z.array(z.string()),
  keyless: z.boolean(),
  response: json,
  views: z
    .array(z.object({ view: z.string().nullable(), options: z.array(option).optional() }))
    .optional(),
});
type Parser = z.infer<typeof parser>;

const config = referenceConfig.parse(await Bun.file(file("scripts/reference.config.json")).json());
const response = await fetch(PARSERS_URL);
if (!response.ok) throw new Error(`GET ${PARSERS_URL} returned ${response.status}`);
const parsers = z
  .object({ data: z.object({ parsers: z.array(parser) }) })
  .parse(await response.json()).data.parsers;
const byName = new Map(parsers.map((entry) => [entry.name, entry]));

const listed = config.parserCategories.flatMap((category) => category.parsers);
const unknown = listed.filter((name) => !byName.has(name));
if (unknown.length > 0) throw new Error(`Not in GET /v1/parsers: ${unknown.join(", ")}`);
const unlisted = parsers.map((entry) => entry.name).filter((name) => !listed.includes(name));
if (unlisted.length > 0) throw new Error(`Not in any category in scripts/reference.config.json: ${unlisted.join(", ")}`);

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const sentence = (text: string) => (/[.!?]$/.test(text) ? text : `${text}.`);
const lowerFirst = (text: string) => `${text.charAt(0).toLowerCase()}${text.slice(1)}`;
const code = (items: string[]) => items.map((item) => `\`${item}\``).join(", ");
const pathOf = (slug: string) => `${OVERVIEW}/${slug}`;
const categoryOf = (name: string) => {
  const category = config.parserCategories.find((item) => item.parsers.includes(name));
  if (category === undefined) throw new Error(`${name} has no category`);
  return category;
};

const frontmatter = (title: string, description: string) => {
  if (description.length > 160) throw new Error(`description is ${description.length} characters: ${description}`);
  return ["---", `title: ${quote(title)}`, `description: ${quote(description)}`, "---", "", GENERATED, ""];
};

const sharedOptions = (() => {
  const counts = new Map<string, { description: string; names: Set<string>; count: number }>();
  for (const entry of parsers) {
    for (const item of entry.options) {
      if (item.description === undefined) continue;
      const key = `${item.name}\n${item.description}`;
      const seen = counts.get(key) ?? { description: item.description, names: new Set([item.name]), count: 0 };
      seen.count++;
      counts.set(key, seen);
    }
  }
  return new Map([...counts].filter(([, seen]) => seen.count >= SHARED_FROM).map(([key, seen]) => [key, seen]));
})();
const isShared = (item: z.infer<typeof option>) => sharedOptions.has(`${item.name}\n${item.description}`);

const namedViews = (entry: Parser) => (entry.views ?? []).flatMap((view) => (view.view === null ? [] : [{ ...view, view: view.view }]));

function optionLines(entry: Parser): string[] {
  const viewNames = [...new Set(namedViews(entry).map((view) => view.view))];
  const top = new Set(entry.options.map((item) => item.name));
  const lines = [
    ...(viewNames.length === 0 ? [] : [`- \`view\`: ${code(viewNames)}.`]),
    ...entry.options.map((item) =>
      item.description === undefined || isShared(item) ? `- \`${item.name}\`` : `- \`${item.name}\`: ${mdxSafe(sentence(item.description))}`,
    ),
    ...namedViews(entry).flatMap((view) =>
      (view.options ?? [])
        .filter((item) => !top.has(item.name))
        .map((item) => `- \`${item.name}\`, with \`view\` \`${view.view}\`${item.description === undefined ? "" : `: ${mdxSafe(lowerFirst(sentence(item.description)))}`}`),
    ),
  ];
  return lines.length === 0 ? [] : ["Options:", ...lines];
}

function entryOf(entry: Parser): string[] {
  return [
    `### \`${entry.name}\``,
    "",
    `${mdxSafe(sentence(entry.takes))} Example: \`${entry.example}\``,
    ...(entry.returns.length === 0 ? [] : ["", `Returns ${code(entry.returns)}.`]),
    ...(entry.keyless ? ["", "Works without an API key when you send no options."] : []),
    ...(optionLines(entry).length === 0 ? [] : ["", ...optionLines(entry)]),
    "",
  ];
}

function categoryPage(slug: string): string {
  const category = config.parserCategories.find((item) => item.slug === slug);
  if (category === undefined) throw new Error(`No category ${slug}`);
  let description = `Parsers for ${category.title.toLowerCase()}:`;
  for (const name of category.parsers) if (`${description} ${name},`.length < 150) description += ` ${name},`;
  description = `${description.replace(/,$/, "")}${description.endsWith(",") ? " and more" : ""}.`;
  return [
    ...frontmatter(category.title, description),
    `Send the example URL to [scrape](/api-reference/endpoint/scrape) with the format \`{"type": "json", "parser": "<name>"}\`. See [Pre-built parsers](/${OVERVIEW}).`,
    "",
    ...category.parsers.flatMap((name) => entryOf(byName.get(name) ?? parsers[0]!)),
  ].join("\n");
}

async function overviewPage(): Promise<string> {
  const sample = byName.get(SAMPLE);
  if (sample === undefined) throw new Error(`${SAMPLE} is not in GET /v1/parsers`);
  const saved = recorded.parse(await Bun.file(file(`scripts/responses/parsers/${SAMPLE}.json`)).json());
  const keyless = parsers.filter((entry) => entry.keyless).length;
  const description = `Read a site's own data as JSON. Name one of ${parsers.length} parsers in a scrape request for Reddit, YouTube, Google Maps, Amazon and more.`;
  return [
    ...frontmatter("Pre-built parsers", description),
    `A parser reads one kind of page on one site and returns its data as JSON. Name it in a \`json\` format of [scrape](/api-reference/endpoint/scrape). The URL must be the kind of page the parser reads, or the call fails with \`invalidRequest\`. ${parsers.length} parsers exist. ${keyless} work without an API key when you send no options.`,
    "",
    "<CodeGroup>",
    curlSnippet(saved.request, true),
    tsSnippet(saved.request, true),
    pythonSnippet(saved.request, true),
    "</CodeGroup>",
    "",
    "The data is in `data.json`.",
    "",
    "```json",
    JSON.stringify(saved.response, null, 2),
    "```",
    "",
    "## Options",
    "",
    "Send options in the `options` object of the format, like `{\"type\": \"json\", \"parser\": \"youtube-transcript\", \"options\": {\"language\": \"en\"}}`. A parser that reads more than one kind of page takes `view`.",
    "",
    "| Option | Meaning |",
    "| --- | --- |",
    ...[...sharedOptions.values()].map((shared) => `| ${code([...shared.names].sort())} | ${mdxSafe(sentence(shared.description))} |`),
    "",
    "## Parsers",
    "",
    "Each page lists the page a parser reads, an example URL, the fields it returns and its options.",
    "",
    ...config.parserCategories.map((category) => `- [${category.title}](/${pathOf(category.slug)}): ${code(category.parsers)}`),
    "",
    "## Read the list from code",
    "",
    "`GET /v1/parsers` is free and needs no API key. Each entry has `takes`, `example`, `options`, `returns`, `price`, `keyless` and a sample `response`. It is the only place that lists each parser's price. See [Pricing](/account/pricing) for the rest.",
    "",
    "```bash",
    "curl -s https://api.stophy.dev/v1/parsers \\",
    `  | jq -r '.data.parsers[] | select(.name | startswith("youtube")) | "\\(.name): \\(.takes)"'`,
    "```",
    "",
  ].join("\n");
}

rmSync(file(`${OVERVIEW}/`).pathname, { recursive: true, force: true });
await Bun.write(file(`${OVERVIEW}.mdx`), await overviewPage());
for (const category of config.parserCategories) await Bun.write(file(`${pathOf(category.slug)}.mdx`), categoryPage(category.slug));

const docs = jsonObject.parse(await Bun.file(file("docs.json")).json());
const found: JsonObject[] = [];
const visit = (node: Json): void => {
  if (Array.isArray(node)) node.forEach(visit);
  else if (isObject(node)) {
    if (node.root === OVERVIEW) found.push(node);
    Object.values(node).forEach(visit);
  }
};
visit(docs.navigation ?? null);
const [group] = found;
if (found.length !== 1 || group === undefined) throw new Error(`docs.json needs one group with root ${OVERVIEW}`);
group.group = "Pre-built parsers";
group.pages = config.parserCategories.map((category) => pathOf(category.slug));

const OLD_PREFIX = "/api-reference/endpoint/";
const destinationOf = (name: string) => `/${pathOf(categoryOf(name).slug)}#${name}`;
const redirects = (Array.isArray(docs.redirects) ? docs.redirects : []).filter((redirect) => !(isObject(redirect) && isString(redirect.source) && redirect.source.startsWith(`/${OVERVIEW}/`)));
for (const redirect of redirects) {
  if (!isObject(redirect) || !isString(redirect.source) || !redirect.source.startsWith(OLD_PREFIX)) continue;
  const name = redirect.source.slice(OLD_PREFIX.length);
  if (byName.has(name)) redirect.destination = destinationOf(name);
}
for (const entry of parsers) redirects.push({ source: `/${OVERVIEW}/${categoryOf(entry.name).slug}/${entry.name}`, destination: destinationOf(entry.name) });
docs.redirects = redirects;
await Bun.write(file("docs.json"), `${JSON.stringify(docs, null, 2)}\n`);

console.log(`Wrote ${config.parserCategories.length} category pages for ${parsers.length} parsers and the overview.`);
