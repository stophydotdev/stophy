import { z } from "zod";
import { json } from "./catalog";
import { mdxSafe, referenceConfig, shorten } from "./reference";
import { curlSnippet, pythonSnippet, tsSnippet } from "./snippets";

const root = new URL("..", import.meta.url);
const file = (path: string) => new URL(path, root);
const PARSERS_URL = process.env.STOPHY_PARSERS_URL ?? "https://api.stophy.dev/v1/parsers";
const GENERATED = "{/* Generated by scripts/gen-parsers.ts from GET /v1/parsers. Do not edit. */}";

const option = z.object({ name: z.string(), description: z.string().optional() });
const parser = z.object({
  name: z.string(),
  takes: z.string(),
  example: z.string(),
  options: z.array(option),
  returns: z.array(z.string()),
  output: z.string().nullable(),
  price: z.string(),
  keyless: z.boolean(),
  response: json,
  views: z.array(z.object({ options: z.array(option) })).optional(),
});
type Parser = z.infer<typeof parser>;

const config = referenceConfig.parse(await Bun.file(file("scripts/reference.config.json")).json());
const response = await fetch(PARSERS_URL);
if (!response.ok) throw new Error(`GET ${PARSERS_URL} returned ${response.status}`);
const parsers = z.object({ data: z.object({ parsers: z.array(parser) }) }).parse(await response.json()).data.parsers;
const byName = new Map(parsers.map((entry) => [entry.name, entry]));

const listed = config.parserPages.flatMap((page) => page.parsers);
const unknown = listed.filter((name) => !byName.has(name));
if (unknown.length > 0) throw new Error(`Not in GET /v1/parsers: ${unknown.join(", ")}`);
const unlisted = parsers.map((entry) => entry.name).filter((name) => !listed.includes(name));
if (unlisted.length > 0) throw new Error(`Not on any parser page in scripts/reference.config.json: ${unlisted.join(", ")}`);

const sentence = (text: string) => (/[.!?]$/.test(text) ? text : `${text}.`);
const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const firstSentence = (text: string) => sentence(text.split(/(?<=\.) /)[0] ?? text);

const requestFor = (entry: Parser) => ({
  method: "POST",
  path: "/v1/scrape",
  body: { url: entry.example, formats: [{ type: "json", parser: entry.name }] },
});

function optionsOf(entry: Parser) {
  const all = [...entry.options, ...(entry.views ?? []).flatMap((view) => view.options)];
  return [...new Map(all.map((item) => [item.name, item])).values()].map(
    (item) => all.find((other) => other.name === item.name && other.description !== undefined) ?? item,
  );
}

function outputText(output: string | null): string {
  if (output === null) return "";
  return output.endsWith(" list") ? `A list of ${output.replace(/ list$/, "")}s: ` : `One ${output}: `;
}

function section(entry: Parser): string[] {
  const options = optionsOf(entry).map((item) =>
    item.description === undefined ? `\`${item.name}\`` : `\`${item.name}\` (${mdxSafe(item.description.replace(/\.$/, ""))})`,
  );
  return [
    `## ${entry.name}`,
    "",
    mdxSafe(sentence(entry.takes)),
    "",
    `- **Example page:** ${entry.example}`,
    `- **Returns:** ${outputText(entry.output)}${entry.returns.map((name) => `\`${name}\``).join(", ")}.`,
    ...(options.length === 0 ? [] : [`- **Options:** ${options.join(", ")}.`]),
    `- **Price:** ${sentence(entry.price)}${entry.keyless ? " Works without an API key." : ""}`,
    "",
    '<Accordion title="Example response">',
    "",
    "```json",
    JSON.stringify(shorten(entry.response), null, 2),
    "```",
    "",
    "</Accordion>",
    "",
  ];
}

function page(definition: (typeof config.parserPages)[number]): string {
  const entries = definition.parsers.map((name) => byName.get(name)).filter((entry) => entry !== undefined);
  const [first] = entries;
  if (first === undefined) throw new Error(`${definition.slug} has no parsers`);
  const request = requestFor(first);
  return [
    "---",
    `title: ${quote(definition.title)}`,
    `description: ${quote(definition.description)}`,
    `og:title: ${quote(`${definition.title} | Stophy`)}`,
    `og:description: ${quote(definition.description)}`,
    `icon: ${quote(definition.icon)}`,
    "---",
    "",
    GENERATED,
    "",
    `Each parser reads one kind of page and returns the site's own data. Send the page's URL to [scrape](/api-reference/endpoint/scrape) with a \`json\` format that names the parser. The data comes back in \`data.json\`.`,
    "",
    "<CodeGroup>",
    curlSnippet(request, true),
    tsSnippet(request, true),
    pythonSnippet(request, true),
    "</CodeGroup>",
    "",
    `Send a parser's options in the same format, like \`{"type": "json", "parser": "${first.name}", "options": {...}}\`. See [Parsers](/guides/parsers) for how they work.`,
    "",
    "| Parser | Reads | Price |",
    "| --- | --- | --- |",
    ...entries.map((entry) => `| [\`${entry.name}\`](#${entry.name}) | ${mdxSafe(firstSentence(entry.takes))} | ${sentence(entry.price)} |`),
    "",
    ...entries.flatMap(section),
  ].join("\n");
}

for (const definition of config.parserPages) {
  await Bun.write(file(`sources/${definition.slug}.mdx`), page(definition));
}
console.log(`Wrote ${config.parserPages.length} parser pages covering ${listed.length} parsers.`);
