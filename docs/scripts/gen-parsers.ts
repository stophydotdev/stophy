import { rmSync } from "node:fs";
import { z } from "zod";
import { type Json, type JsonObject, isObject, isString, json, jsonObject } from "./catalog";
import { anonymize, mdxSafe, money, recorded, referenceConfig, shorten } from "./reference";
import { curlSnippet, pythonSnippet, tsSnippet } from "./snippets";

const root = new URL("..", import.meta.url);
const file = (path: string) => new URL(path, root);
const PARSERS_URL = process.env.STOPHY_PARSERS_URL ?? "https://api.stophy.dev/v1/parsers";
const GENERATED = "{/* Generated by scripts/gen-parsers.ts from GET /v1/parsers. Do not edit. */}";
const OVERVIEW = "scrape/prebuilt-parsers";
const KEYLESS_LIMITS = "up to 10 calls a minute and 50 calls a day per IP address";

const option = z.object({ name: z.string(), description: z.string().optional() });
const parser = z.object({
  name: z.string(),
  takes: z.string(),
  example: z.string(),
  options: z.array(option),
  returns: z.array(z.string()),
  output: z.string().nullable(),
  price: z.string(),
  keyless: z.boolean(),
  response: json,
  views: z
    .array(
      z.object({
        view: z.string().nullable(),
        price: z.string().optional(),
        keyless: z.boolean().optional(),
        options: z.array(option).optional(),
      }),
    )
    .optional(),
});
type Parser = z.infer<typeof parser>;

const config = referenceConfig.parse(await Bun.file(file("scripts/reference.config.json")).json());
const response = await fetch(PARSERS_URL);
if (!response.ok) throw new Error(`GET ${PARSERS_URL} returned ${response.status}`);
const parsers = z
  .object({ data: z.object({ parsers: z.array(parser) }) })
  .parse(await response.json())
  .data.parsers.map((entry) => ({
    ...entry,
    price: money(entry.price),
    views: entry.views?.map((view) => ({ ...view, price: view.price === undefined ? undefined : money(view.price) })),
  }));
const byName = new Map(parsers.map((entry) => [entry.name, entry]));

const listed = config.parserCategories.flatMap((category) => category.parsers);
const unknown = listed.filter((name) => !byName.has(name));
if (unknown.length > 0) throw new Error(`Not in GET /v1/parsers: ${unknown.join(", ")}`);
const unlisted = parsers.map((entry) => entry.name).filter((name) => !listed.includes(name));
if (unlisted.length > 0) throw new Error(`Not in any category in scripts/reference.config.json: ${unlisted.join(", ")}`);

const sentence = (text: string) => (/[.!?]$/.test(text) ? text : `${text}.`);
const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const lowerFirst = (text: string) => `${text.charAt(0).toLowerCase()}${text.slice(1)}`;
const firstSentence = (text: string) => (text.split(/(?<=\.) (?=[A-Z])/)[0] ?? text).replace(/\.$/, "");
const list = (items: string[]) => (items.length < 2 ? items.join("") : `${items.slice(0, -1).join(", ")} and ${items.at(-1)}`);
const mostCommon = (items: string[]) => {
  const counts = new Map<string, number>();
  for (const item of items) counts.set(item, (counts.get(item) ?? 0) + 1);
  return [...counts].reduce((best, entry) => (entry[1] > best[1] ? entry : best))[0];
};
const code = (items: string[]) => list(items.map((item) => `\`${item}\``));

const titleOf = (name: string) =>
  name
    .split("-")
    .map((word, index) => config.parserBrands[word] ?? (index === 0 ? `${word.charAt(0).toUpperCase()}${word.slice(1)}` : word))
    .join(" ");

const categoryOf = (name: string) => {
  const category = config.parserCategories.find((item) => item.parsers.includes(name));
  if (category === undefined) throw new Error(`${name} has no category`);
  return category;
};

const relatedTo = (name: string) => {
  const words = name.split("-");
  const shared = (other: string) => {
    const theirs = other.split("-");
    const firstMiss = words.findIndex((word, index) => theirs[index] !== word);
    return firstMiss === -1 ? words.length : firstMiss;
  };
  const others = listed.filter((other) => other !== name);
  const sameSite = others.filter((other) => shared(other) !== 0).sort((a, b) => shared(b) - shared(a));
  const sameGroup = categoryOf(name).parsers.filter((other) => other !== name && !sameSite.includes(other));
  return [...sameSite, ...sameGroup].slice(0, 3);
};

const pathOf = (name: string) => `${OVERVIEW}/${categoryOf(name).slug}/${name}`;

const recordedFor = async (name: string) => {
  const saved = Bun.file(file(`scripts/responses/parsers/${name}.json`));
  return (await saved.exists()) ? recorded.parse(await saved.json()) : undefined;
};

const requestFor = (entry: Parser) => ({
  method: "POST",
  path: "/v1/scrape",
  body: { url: entry.example, formats: [{ type: "json", parser: entry.name }] },
});

const codeGroup = (request: ReturnType<typeof requestFor>) => [
  "<CodeGroup>",
  curlSnippet(request, true),
  tsSnippet(request, true),
  pythonSnippet(request, true),
  "</CodeGroup>",
];

const SEO_TAILS = [" Send the page to scrape.", " Examples in cURL, TypeScript and Python.", " Works without an API key."];

function seoText(lead: string, price: string, keyless: boolean): string {
  let text = lead;
  for (const part of [` ${sentence(price)}`, ...(keyless ? SEO_TAILS : SEO_TAILS.slice(0, 2))]) {
    if (text.length < 120 && `${text}${part}`.length <= 160) text = `${text}${part}`;
  }
  if (text.length < 120 || text.length > 160) throw new Error(`description is ${text.length} characters: ${text}`);
  return text;
}

const frontmatter = (title: string, description: string) => [
  "---",
  `title: ${quote(title)}`,
  `description: ${quote(description)}`,
  `og:title: ${quote(`${title} | Stophy`)}`,
  `og:description: ${quote(description)}`,
  "---",
  "",
  GENERATED,
  "",
];

function parserDescription(entry: Parser): string {
  const subject = lowerFirst(firstSentence(entry.takes));
  const comma = subject.search(/[,;:]/);
  const clause = comma > 0 ? subject.slice(0, comma) : subject;
  const cut = clause.length > 90 ? clause.slice(0, clause.lastIndexOf(" ", 90)) : clause;
  return seoText(`Read ${cut} as JSON with the ${entry.name} parser.`, entry.price, entry.keyless);
}

function outputPhrase(entry: Parser): string {
  const { output } = entry;
  if (output === null) return "its data";
  return output.endsWith(" list") ? `a list of ${output.replace(/ list$/, "")}s` : `one ${output}`;
}

function keyNote(entry: Parser): string {
  return entry.keyless
    ? `This parser works without an API key when you send no options, ${KEYLESS_LIMITS}. See [Rate limits](/production/rate-limits). To lift the limits, get an API key in the [Quickstart](/quickstart).`
    : "Get an API key in the [Quickstart](/quickstart).";
}

const namedViews = (entry: Parser) => (entry.views ?? []).flatMap((view) => (view.view === null ? [] : [{ ...view, view: view.view }]));

const viewPrices = (entry: Parser) =>
  namedViews(entry).flatMap((view) => {
    const price = view.price !== undefined && view.price !== entry.price ? ` costs ${lowerFirst(view.price)}` : "";
    const key = view.keyless === false && entry.keyless ? " needs an API key" : "";
    if (price === "" && key === "") return [];
    return [` The \`${view.view}\` view${price}${price !== "" && key !== "" ? " and" : ""}${key}.`];
  });

function optionsSection(entry: Parser): string[] {
  const described = entry.options.filter((item) => item.description !== undefined);
  const bare = entry.options.filter((item) => item.description === undefined).map((item) => item.name);
  const viewNames = [...new Set((entry.views ?? []).flatMap((view) => (view.view === null ? [] : [view.view])))];
  const topNames = new Set(entry.options.map((item) => item.name));
  const viewOptions = namedViews(entry).flatMap((view) =>
    (view.options ?? [])
      .filter((item) => !topNames.has(item.name) && item.description !== undefined)
      .map((item) => `| \`${item.name}\` | With \`view\` \`${view.view}\`: ${mdxSafe(lowerFirst(sentence(item.description ?? "")))} |`),
  );
  const table = [
    ...(viewNames.length === 0 ? [] : [`| \`view\` | Picks one of the answers this parser can give: ${code(viewNames)}. |`]),
    ...described.map((item) => `| \`${item.name}\` | ${mdxSafe(sentence(item.description ?? ""))} |`),
    ...viewOptions,
  ];
  const lines = ["## Options", "", `Send options in the \`options\` object of the \`json\` format.`, ""];
  if (table.length > 0) lines.push("| Option | What it does |", "| --- | --- |", ...table, "");
  if (bare.length > 0) lines.push(`${table.length > 0 ? "It also takes" : "It takes"} ${code(bare)}.`, "");
  if (table.length === 0 && bare.length === 0) return ["## Options", "", "This parser takes no options.", ""];
  return lines;
}

function limitsSection(entry: Parser): string[] {
  const pages = entry.options.some((item) => item.name === "cursor");
  return [
    "## Limits and errors",
    "",
    entry.takes.startsWith("Any ")
      ? `- The URL can be ${mdxSafe(lowerFirst(sentence(entry.takes)))}`
      : `- The URL must be ${mdxSafe(lowerFirst(sentence(entry.takes)))} Any other URL fails with \`invalidRequest\`.`,
    ...(pages ? ["- To read the next page, send the `cursor` from the response as the `cursor` option. Paging needs an API key."] : []),
    "- The answer comes back in `data.json`. If the page cannot be read, the call fails with an error code from [Errors](/api-reference/errors).",
    "",
  ];
}

const trimmedResponse = (entry: Parser, saved: Awaited<ReturnType<typeof recordedFor>>): JsonObject => {
  if (saved !== undefined) return saved.response;
  return anonymize(jsonObject.parse({ success: true, data: { json: shorten(entry.response) } }));
};

async function parserPage(entry: Parser): Promise<string> {
  const title = titleOf(entry.name);
  const saved = await recordedFor(entry.name);
  const request = saved?.request ?? requestFor(entry);
  const siblings = relatedTo(entry.name);
  const returned = entry.returns.length === 0 ? "" : ` Its fields include ${code(entry.returns)}.`;
  return [
    ...frontmatter(title, parserDescription(entry)),
    `Reads ${mdxSafe(lowerFirst(firstSentence(entry.takes)))}${firstSentence(entry.takes).includes(",") ? "," : ""} and returns ${outputPhrase(entry)} as JSON.`,
    "",
    "## Make a request",
    "",
    `Send the page's URL to [scrape](/api-reference/endpoint/scrape) with a \`json\` format that names the parser. ${keyNote(entry)}`,
    "",
    ...codeGroup(request),
    "",
    "## Read the response",
    "",
    `The parser's data is in \`data.json\`.${returned} This ${saved === undefined ? "sample is cut to the first items" : "real response is cut to the first items"}.`,
    "",
    "```json",
    JSON.stringify(trimmedResponse(entry, saved), null, 2),
    "```",
    "",
    ...optionsSection(entry),
    "## Price",
    "",
    `${sentence(entry.price)}${entry.keyless ? " Works without an API key, within the free limits." : ""}${viewPrices(entry).join("")} See [Pricing](/account/pricing).`,
    "",
    ...limitsSection(entry),
    "## Related",
    "",
    `- [Pre-built parsers](/${OVERVIEW}) lists every parser.`,
    "- [Scrape](/scrape/overview) has the options every scrape takes.",
    ...siblings.map((name) => `- [${titleOf(name)}](/${pathOf(name)})`),
    "",
  ].join("\n");
}

function overviewTable(names: string[]): string[] {
  return [
    "| Parser | Reads | Price |",
    "| --- | --- | --- |",
    ...names.flatMap((name) => {
      const entry = byName.get(name);
      return entry === undefined ? [] : [`| [${titleOf(name)}](/${pathOf(name)}) | ${mdxSafe(sentence(firstSentence(entry.takes)))} | ${sentence(entry.price)} |`];
    }),
    "",
  ];
}

async function overviewPage(): Promise<string> {
  const sampleName = "youtube-transcript";
  const sample = byName.get(sampleName);
  if (sample === undefined) throw new Error(`${sampleName} is not in GET /v1/parsers`);
  const saved = await recordedFor(sampleName);
  const request = saved?.request ?? requestFor(sample);
  const keyless = parsers.filter((entry) => entry.keyless).length;
  const commonPrice = mostCommon(parsers.map((entry) => entry.price));
  const description = `Read a site's own data as JSON. Name one of ${parsers.length} parsers in a scrape request for Reddit, YouTube, Google Maps, Amazon and more.`;
  if (description.length < 120 || description.length > 160) throw new Error(`overview description is ${description.length} characters`);
  const format = `{"type": "json", "parser": "${sampleName}", "options": {"language": "en"}}`;
  return [
    ...frontmatter("Pre-built parsers", description),
    `A parser reads one kind of page on one site and returns the site's own data as JSON. A Reddit search page comes back as posts, a YouTube video link as its transcript, a Google Maps search as places. There are ${parsers.length} parsers.`,
    "",
    "## Make a request",
    "",
    "Send the page's URL to [scrape](/api-reference/endpoint/scrape) with a `json` format that names one parser. Get an API key in the [Quickstart](/quickstart).",
    "",
    ...codeGroup(request),
    "",
    "## Read the response",
    "",
    `The parser's data is in \`data.json\`. The URL must be the kind of page the parser reads, or the call fails with \`invalidRequest\`. This real response is cut to the first items.`,
    "",
    "```json",
    JSON.stringify(trimmedResponse(sample, saved), null, 2),
    "```",
    "",
    "## Options",
    "",
    `Each parser has its own options. Send them in the \`options\` object of the format, like \`${format}\`. A parser's page lists the options it takes. Some parsers read more than one kind of page and list each as a view. Set \`options.view\` to pick one where the page says so. To read the next page of results, send the \`cursor\` from the response as the \`cursor\` option.`,
    "",
    "## Choose a parser",
    "",
    ...config.parserCategories.flatMap((category) => [`### ${category.title}`, "", ...overviewTable(category.parsers)]),
    "## Price",
    "",
    `Each parser has its own price per call, most of them ${commonPrice}. ${keyless} parsers work without an API key when you send no options, ${KEYLESS_LIMITS}. See [Rate limits](/production/rate-limits). Paging and other options need an API key. See [Pricing](/account/pricing).`,
    "",
    "## Read the list from code",
    "",
    "`GET /v1/parsers` returns every parser. It is free and needs no API key.",
    "",
    "```bash",
    "curl -s https://api.stophy.dev/v1/parsers \\",
    `  | jq -r '.data.parsers[] | select(.name | startswith("youtube")) | "\\(.name): \\(.takes)"'`,
    "```",
    "",
    "Each entry has `takes` (the page it reads), an `example` URL, its `options`, the fields it `returns`, its `price`, `keyless: true` when it works without an API key, and a sample `response`. See [List parsers](/api-reference/endpoint/list-parsers).",
    "",
    "## Choose another format",
    "",
    "- [JSON](/scrape/json) returns an object in the shape you describe, from any page.",
    "- [Markdown](/scrape/markdown) returns the page text.",
    "- [Scrape](/scrape/overview) lists every format and option.",
    "",
  ].join("\n");
}

rmSync(file(`${OVERVIEW}/`).pathname, { recursive: true, force: true });
await Bun.write(file(`${OVERVIEW}.mdx`), await overviewPage());
for (const entry of parsers) await Bun.write(file(`${pathOf(entry.name)}.mdx`), await parserPage(entry));

const docs = jsonObject.parse(await Bun.file(file("docs.json")).json());
const found: JsonObject[] = [];
const visit = (node: Json): void => {
  if (Array.isArray(node)) node.forEach(visit);
  else if (isObject(node)) {
    if (node.group === "Parse" && node.root === OVERVIEW) found.push(node);
    Object.values(node).forEach(visit);
  }
};
visit(docs.navigation ?? null);
const [group] = found;
if (found.length !== 1 || group === undefined) throw new Error(`docs.json needs one group named Parse with root ${OVERVIEW}`);
group.pages = config.parserCategories.map((category) => ({ group: category.title, pages: category.parsers.map(pathOf) }));

const OLD_PREFIX = "/api-reference/endpoint/";
if (Array.isArray(docs.redirects)) {
  for (const redirect of docs.redirects) {
    if (!isObject(redirect) || !isString(redirect.source) || !redirect.source.startsWith(OLD_PREFIX)) continue;
    const name = redirect.source.slice(OLD_PREFIX.length);
    if (byName.has(name)) redirect.destination = `/${pathOf(name)}`;
  }
}
await Bun.write(file("docs.json"), `${JSON.stringify(docs, null, 2)}\n`);

console.log(`Wrote ${parsers.length} parser pages in ${config.parserCategories.length} categories and the overview.`);
