import { readFileSync } from "node:fs";
import { type CatalogEndpoint, type Json, type JsonObject, fetchCatalog, isObject, isString, jsonObject } from "./catalog";
import { mdxSafe, recorded, referenceConfig } from "./reference";
import { curlSnippet } from "./snippets";

interface Operation {
  id: string;
  method: string;
  path: string;
  summary: string;
  description: string;
  keyless: boolean;
  isUpload: boolean;
  catalog: CatalogEndpoint | undefined;
}

const root = new URL("..", import.meta.url);
const file = (path: string) => new URL(path, root);
const SPEC_PATH = "api-reference/openapi.json";
const ENDPOINT_DIR = "api-reference/endpoint";
const GENERATED = "{/* Generated by scripts/gen-reference.ts. Do not edit. */}";
const RESPONSE_DEPTH = 4;
const OMITTED_FIELDS = new Set(["proxyUsed"]);

const config = referenceConfig.parse(await Bun.file(file("scripts/reference.config.json")).json());
const spec = jsonObject.parse(await Bun.file(file(SPEC_PATH)).json());
const catalog = await fetchCatalog();
const catalogByPath = new Map(catalog.endpoints.map((endpoint) => [`${endpoint.method} ${endpoint.path}`, endpoint]));

const slugOf = (id: string) => id.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`).replace(/^get-/, "");
const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const sentence = (text: string) => (/[.!?]$/.test(text) ? text : `${text}.`);
const firstSentence = (text: string) => text.split(/(?<=\.) (?=[A-Z])/)[0] ?? text;

function operations(): Operation[] {
  const list: Operation[] = [];
  for (const [path, item] of Object.entries(isObject(spec.paths) ? spec.paths : {})) {
    for (const [method, op] of Object.entries(isObject(item) ? item : {})) {
      if (!isObject(op) || !isString(op.operationId)) continue;
      const upper = method.toUpperCase();
      const entry = catalogByPath.get(`${upper} ${path}`);
      const security = Array.isArray(op.security) ? op.security : undefined;
      list.push({
        id: op.operationId,
        method: upper,
        path,
        summary: isString(op.summary) ? op.summary : op.operationId,
        description: isString(op.description) ? op.description : "",
        keyless: entry?.keyless ?? security?.length === 0,
        isUpload: isObject(op.requestBody) && isObject(op.requestBody.content) && op.requestBody.content["application/json"] === undefined,
        catalog: entry,
      });
    }
  }
  return list;
}

function titleOf(op: Operation): string {
  const title = config.titles[op.id];
  if (title === undefined) throw new Error(`No title for ${op.id} in scripts/reference.config.json`);
  return title;
}

function seoDescription(op: Operation): string {
  const text = config.descriptions[op.id] ?? sentence(firstSentence(op.summary));
  if (text.length > 160) throw new Error(`${op.id}: description is ${text.length} characters: ${text}`);
  return text;
}

const PAGES_NOTE = " Pages with cursor.";

const JOB_PAGES = new Map([
  ["crawlStatus", { errors: "[Crawl errors](/api-reference/endpoint/crawl-errors)", where: "/crawl/async" }],
  ["batchScrapeStatus", { errors: "[Batch scrape errors](/api-reference/endpoint/batch-scrape-errors)", where: "/batches/results" }],
]);

function pagesSection(op: Operation): string[] {
  if (!op.description.includes(PAGES_NOTE)) return [];
  const job = JOB_PAGES.get(op.id);
  if (job === undefined) {
    return ["## Pages", "", "Send the `cursor` of a full answer back, with the same filters, to read the next page. No `cursor` means you have read everything.", ""];
  }
  return [
    "## Pages",
    "",
    `Poll until \`status\` is \`completed\`, \`failed\` or \`cancelled\`, then call \`next\` until it is gone. An answer holds up to 100 finished pages or 2 MB, and a page's URL is in \`metadata.url\`. See [Read the results](${job.where}).`,
    "",
    `\`failed\` counts the pages that could not be read. \`errors\` lists the failed pages in this answer, and \`error\` is set only when the whole job failed. ${job.errors} lists every failed page.`,
    "",
  ];
}

const ROBOTS_TEXT = new Map([
  ["crawlErrors", "`robotsBlocked` lists up to 1,000 links that a robots.txt the crawl read did not allow. A link whose robots.txt could not be read is skipped and not listed."],
  ["batchScrapeErrors", "A batch does not apply robots.txt, so `robotsBlocked` is always empty."],
]);

function errorsSection(op: Operation): string[] {
  const robots = ROBOTS_TEXT.get(op.id);
  if (robots === undefined) return [];
  return [
    "## Failed pages",
    "",
    `Lists up to 1,000 failed pages with \`url\`, \`code\`, \`message\`, \`retryable\` and \`at\`. \`isTruncated\` is \`true\` when there are more. Retry a page when \`retryable\` is \`true\`. ${robots}`,
    "",
  ];
}

const KEYLESS_NOTE = "<Note>Works without an API key within the free limits. See [Rate limits](/production/rate-limits).</Note>";
const NO_KEY_NOTE = "<Note>Needs no API key.</Note>";

const capDepth = (value: Json, depth = RESPONSE_DEPTH): Json => {
  if (Array.isArray(value)) return depth === 0 ? "…" : value.map((item) => capDepth(item, depth - 1));
  if (isObject(value)) return depth === 0 ? "…" : Object.fromEntries(Object.entries(value).filter(([field]) => !OMITTED_FIELDS.has(field)).map(([field, item]) => [field, capDepth(item, depth - 1)]));
  return value;
};

function examples(op: Operation): string[] {
  const saved = () => JSON.parse(readFileSync(file(`scripts/responses/${op.id}.json`), "utf8"));
  const call = config.notCalled[op.id] === undefined ? recorded.parse(saved()) : undefined;
  const query = new URLSearchParams(config.calls[op.id]?.query);
  const request = call?.request ?? { method: op.method, path: `${op.path}${query.size === 0 ? "" : `?${query}`}` };
  const keyed = !(op.keyless && op.catalog === undefined);
  if (op.isUpload) return [];
  return [
    "<RequestExample>",
    curlSnippet(request, keyed),
    "</RequestExample>",
    ...(call === undefined
      ? []
      : ["", "<ResponseExample>", `\`\`\`json ${call.status}`, JSON.stringify(capDepth(call.response), null, 2), "```", "</ResponseExample>"]),
  ];
}

function getTwinLine(op: Operation): string[] {
  const twin = byId.get(config.alsoGet[op.id] ?? "");
  return twin === undefined ? [] : [`This also answers \`GET ${twin.path}\`, with the same fields as query parameters.`, ""];
}

function page(op: Operation): string {
  const title = titleOf(op);
  const description = seoDescription(op);
  const intro = mdxSafe(firstSentence(op.catalog?.bestWhen ?? ""));
  const notCalled = config.notCalled[op.id];
  return [
    "---",
    `title: ${quote(title)}`,
    `description: ${quote(description)}`,
    `openapi: ${quote(`${SPEC_PATH} ${op.method} ${op.path}`)}`,
    "---",
    "",
    GENERATED,
    "",
    ...(intro === "" ? [] : [intro, ""]),
    ...getTwinLine(op),
    ...(op.keyless ? [op.catalog === undefined ? NO_KEY_NOTE : KEYLESS_NOTE, ""] : []),
    ...pagesSection(op),
    ...errorsSection(op),
    ...(notCalled === undefined ? [] : [`<Warning>${notCalled}</Warning>`, ""]),
    ...examples(op),
    "",
  ].join("\n");
}

const ops = operations();
const byId = new Map(ops.map((op) => [op.id, op]));
const grouped = config.groups.flatMap((group) => group.operations);
const unknown = grouped.filter((id) => !byId.has(id));
if (unknown.length > 0) throw new Error(`Not in ${SPEC_PATH}: ${unknown.join(", ")}`);
const twins = new Set(Object.values(config.alsoGet));
const ungrouped = ops.filter((op) => !grouped.includes(op.id) && !twins.has(op.id)).map((op) => op.id);
if (ungrouped.length > 0) throw new Error(`Not in any group in scripts/reference.config.json: ${ungrouped.join(", ")}`);

for (const existing of new Bun.Glob("*.mdx").scanSync(file(`${ENDPOINT_DIR}/`).pathname)) {
  await Bun.file(file(`${ENDPOINT_DIR}/${existing}`)).delete();
}
for (const op of ops.filter((op) => !twins.has(op.id))) await Bun.write(file(`${ENDPOINT_DIR}/${slugOf(op.id)}.mdx`), page(op));

const docs = jsonObject.parse(await Bun.file(file("docs.json")).json());
const tabs = isObject(docs.navigation) && Array.isArray(docs.navigation.tabs) ? docs.navigation.tabs.filter(isObject) : [];
const reference = tabs.find((tab) => tab.tab === "API Reference");
if (reference === undefined) throw new Error("docs.json needs the API Reference tab");
const fixed = (Array.isArray(reference.groups) ? reference.groups.filter(isObject) : []).filter((group) => group.group === "Using the API");
const groups: JsonObject[] = config.groups.map((group) => ({
  group: group.group,
  pages: group.operations.map((id) => `${ENDPOINT_DIR}/${slugOf(id)}`),
}));
reference.groups = [...fixed, ...groups];
await Bun.write(file("docs.json"), `${JSON.stringify(docs, null, 2)}\n`);

console.log(`Wrote ${ops.length - twins.size} endpoint pages in ${groups.length} groups.`);
