import {
  isRecord,
  isString,
  type JsonObject,
  type JsonValue,
} from "../packages/typescript/src/json";

const root = new URL("..", import.meta.url);
const specUrl = new URL("openapi.json", root);
const typesUrl = new URL("packages/typescript/src/generated/types.gen.ts", root);
const outUrl = new URL("packages/typescript/src/generated/surface.gen.ts", root);
const parsersUrl = new URL("parsers.json", root);
const parsersOutUrl = new URL("packages/typescript/src/generated/parsers.gen.ts", root);

const spec: JsonValue = JSON.parse(await Bun.file(specUrl).text());
const types = await Bun.file(typesUrl).text();
const operations = operationsFrom(spec);

for (const operation of operations) {
  const name = pascal(operation.id);
  if (operation.input !== "none" && !types.includes(`export type ${name}Data =`)) {
    throw new Error(`Generated types are missing ${name}Data. Run openapi-ts first.`);
  }
  if (!types.includes(`export type ${name}Response =`)) {
    throw new Error(`Generated types are missing ${name}Response. Run openapi-ts first.`);
  }
}

const typeNames = new Set<string>();
for (const operation of operations) {
  const name = pascal(operation.id);
  typeNames.add(`${name}Response`);
  if (operation.input !== "none") typeNames.add(`${name}Data`);
}

const tree = buildTree(operations);
const namespaces = [...tree.children.keys()];
const lines = [
  "// Generated by scripts/gen-surface.ts. Do not edit.",
  "",
  'import { post, postOptional, send, sendEmpty, sendOptional } from "../bind";',
  "import type {",
  ...[...typeNames].sort().map((name) => `\t${name},`),
  '} from "./types.gen";',
  'import type { Caller } from "../transport";',
  "",
  "function bindSurface(call: Caller) {",
  "\treturn {",
  ...emitObject(tree, 2),
  "\t};",
  "}",
  "",
  "type BoundSurface = ReturnType<typeof bindSurface>;",
  "",
  "export class Surface {",
  ...namespaces.map((name) => `\treadonly ${name}: BoundSurface["${name}"];`),
  "",
  "\tconstructor(call: Caller) {",
  "\t\tconst bound = bindSurface(call);",
  ...namespaces.map((name) => `\t\tthis.${name} = bound.${name};`),
  "\t}",
  "}",
  "",
];

await Bun.write(outUrl, lines.join("\n"));
console.log(`Wrote ${operations.length} operations to ${outUrl.pathname}.`);

const parsers: JsonValue = JSON.parse(await Bun.file(parsersUrl).text());
if (!Array.isArray(parsers) || !parsers.every(isString) || parsers.length === 0) {
  throw new Error("parsers.json is not a list of parser names. Run sync first.");
}
await Bun.write(
  parsersOutUrl,
  [
    "// Generated by scripts/gen-surface.ts. Do not edit.",
    "",
    "export type ParserName =",
    ...parsers.map(
      (name, index) => `\t| ${JSON.stringify(name)}${index === parsers.length - 1 ? ";" : ""}`,
    ),
    "",
  ].join("\n"),
);
console.log(`Wrote ${parsers.length} parser names to ${parsersOutUrl.pathname}.`);

type Method = "get" | "post" | "delete";

type Input = "none" | "body" | "optionalBody" | "path" | "query" | "pathAndQuery";

interface Operation {
  id: string;
  method: Method;
  path: string;
  input: Input;
  segments: string[];
}

interface Node {
  children: Map<string, Node>;
  operation?: Operation;
}

function operationsFrom(value: JsonValue): Operation[] {
  if (!isRecord(value) || !isRecord(value.paths)) {
    throw new Error("OpenAPI document has no paths.");
  }
  const operations: Operation[] = [];
  for (const [path, item] of Object.entries(value.paths)) {
    if (!isRecord(item)) continue;
    for (const method of ["get", "post", "delete"] as const) {
      const operation = item[method];
      if (isRecord(operation)) operations.push(operationFrom(path, method, operation));
    }
  }
  return operations;
}

function operationFrom(path: string, method: Method, operation: JsonObject): Operation {
  if (!isString(operation.operationId)) {
    throw new Error(`${method.toUpperCase()} ${path} is missing operationId.`);
  }
  const id = operation.operationId;
  const parts = path.split("/").filter((segment) => segment.length > 0 && segment !== "v1");
  const named = parts.filter((segment) => !segment.startsWith("{"));
  if (named.length === 0) throw new Error(`Cannot namespace ${path}.`);
  const secondary = method === "delete" || named.length < parts.length;
  return {
    id,
    method,
    path,
    input: inputOf(method, operation),
    segments: secondary ? [...named, leafName(id, named)] : named,
  };
}

function leafName(operationId: string, segments: string[]): string {
  const words = wordsOf(operationId);
  const node = segments.flatMap(wordsOf);
  const matches = (offset: number) => node.every((word, index) => words[offset + index] === word);
  const rest = matches(0)
    ? words.slice(node.length)
    : matches(words.length - node.length)
      ? words.slice(0, words.length - node.length)
      : [];
  if (rest.length === 0) throw new Error(`Cannot name ${operationId} under ${segments.join(".")}.`);
  return rest.map((word, index) => (index === 0 ? word : pascal(word))).join("");
}

function wordsOf(value: string): string[] {
  return value
    .replaceAll(/([a-z0-9])([A-Z])/g, "$1 $2")
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((word) => word.length > 0);
}

function inputOf(method: Method, operation: JsonObject): Input {
  if (method === "post") return requiredFields(operation).length > 0 ? "body" : "optionalBody";
  const locations = new Set(parametersOf(operation));
  if (locations.has("path")) return locations.has("query") ? "pathAndQuery" : "path";
  return locations.has("query") ? "query" : "none";
}

function parametersOf(operation: JsonObject): string[] {
  if (!Array.isArray(operation.parameters)) return [];
  return operation.parameters.flatMap((parameter) => {
    if (!isRecord(parameter)) return [];
    if (isString(parameter.in)) return [parameter.in];
    return isString(parameter.$ref) && parameter.$ref.startsWith("#/components/parameters/")
      ? ["query"]
      : [];
  });
}

function requiredFields(operation: JsonObject): string[] {
  const body = operation.requestBody;
  if (!isRecord(body) || !isRecord(body.content)) return [];
  const json = body.content["application/json"];
  if (!isRecord(json)) return [];
  return requiredIn(json.schema);
}

function requiredIn(schema: JsonValue | undefined): string[] {
  if (!isRecord(schema)) return [];
  const branches = schema.oneOf ?? schema.anyOf;
  if (Array.isArray(branches)) return branches.flatMap(requiredIn);
  if (!Array.isArray(schema.required)) return [];
  return schema.required.filter(isString);
}

function buildTree(operations: Operation[]): Node {
  const root: Node = { children: new Map() };
  for (const operation of operations) {
    let node = root;
    for (const segment of operation.segments) {
      const child = node.children.get(segment) ?? { children: new Map() };
      node.children.set(segment, child);
      node = child;
    }
    node.operation = operation;
  }
  return root;
}

function emitObject(node: Node, depth: number): string[] {
  const pad = "\t".repeat(depth);
  const lines: string[] = [];
  for (const [name, child] of node.children) {
    lines.push(`${pad}${name}: ${emitValue(child, depth)},`);
  }
  return lines;
}

function emitValue(node: Node, depth: number): string {
  const call = node.operation ? emitCall(node.operation) : undefined;
  if (!call) {
    return `{\n${emitObject(node, depth + 1).join("\n")}\n${"\t".repeat(depth)}}`;
  }
  if (node.children.size === 0) return call;
  const fields = emitObject(node, depth + 2).join("\n");
  return `Object.assign(${call}, {\n${fields}\n${"\t".repeat(depth + 1)}})`;
}

function emitCall(operation: Operation): string {
  const name = pascal(operation.id);
  const path = JSON.stringify(operation.path);
  const method = JSON.stringify(operation.method.toUpperCase());
  switch (operation.input) {
    case "body":
      return `post<${name}Data["body"], ${name}Response>(${path}, call)`;
    case "optionalBody":
      return `postOptional<${name}Data["body"], ${name}Response>(${path}, call)`;
    case "path":
      return `send<${name}Data["path"], ${name}Response>(${method}, ${path}, call)`;
    case "pathAndQuery":
      return `send<${name}Data["path"] & NonNullable<${name}Data["query"]>, ${name}Response>(${method}, ${path}, call)`;
    case "query":
      return `sendOptional<NonNullable<${name}Data["query"]>, ${name}Response>(${method}, ${path}, call)`;
    case "none":
      return `sendEmpty<${name}Response>(${method}, ${path}, call)`;
  }
}

function pascal(operationId: string): string {
  return operationId.charAt(0).toUpperCase() + operationId.slice(1);
}
